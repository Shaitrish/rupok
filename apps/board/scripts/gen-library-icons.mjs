// Extracts the Solar icons the Library uses (all style variants) into
// src/library/icons.generated.ts. Kept separate from gen-icons.mjs so the
// Library can add icons without touching the board's icon set.
// Run: node scripts/gen-library-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const set = JSON.parse(readFileSync(new URL("../node_modules/@iconify-json/solar/icons.json", import.meta.url)));
const VARIANTS = ["linear", "line-duotone", "broken", "bold", "bold-duotone", "outline"];

// logical name -> Solar base name
const MAP = {
  library: "folder-with-files",
  recent: "clock-circle",
  mine: "folder-with-files",
  shared: "inbox-in",
  copies: "documents",
  trash: "trash-bin-trash",
  cloud: "cloud",
  folder: "folder",
  folderAdd: "add-folder",
  course: "square-academic-cap",
  lesson: "notebook-minimalistic",
  search: "magnifer",
  sort: "sort-vertical",
  grid: "widget",
  list: "list",
  rename: "pen-new-square",
  move: "move-to-folder",
  zip: "archive-down",
  check: "check-circle",
  warn: "danger-triangle",
  lock: "lock",
  teacher: "presentation-graph",
  student: "notebook",
  laptop: "laptop",
  browser: "database",
  chevron: "alt-arrow-right",
  chevronDown: "alt-arrow-down",
  refresh: "refresh",
  shield: "shield-check",
  copy: "copy",
};

function body(name) {
  const icon = set.icons[name];
  if (icon) return icon.body;
  const alias = set.aliases?.[name];
  if (alias) return body(alias.parent);
  return null;
}

const out = {};
for (const [logical, base] of Object.entries(MAP)) {
  out[logical] = {};
  for (const v of VARIANTS) {
    const b = body(`${base}-${v}`);
    if (!b) throw new Error(`missing solar icon ${base}-${v}`);
    out[logical][v] = b;
  }
}

const names = Object.keys(MAP).map((n) => JSON.stringify(n)).join(" | ");
const ts = `// Generated by scripts/gen-library-icons.mjs from Solar icons (CC BY 4.0, 480 Design).
// Do not edit by hand.
import type { IconVariant } from "../icons.generated";
export type LibIconName = ${names};
export const LIB_ICONS: Record<LibIconName, Record<IconVariant, string>> = ${JSON.stringify(out)};
`;
writeFileSync(new URL("../src/library/icons.generated.ts", import.meta.url), ts);
console.log(`wrote ${Object.keys(MAP).length} icons`);
