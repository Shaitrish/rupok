function body(name) {
  const icon = set.icons[name];
  if (icon) return icon.body;
  const alias = set.aliases?.[name];
  if (alias) return body(alias.parent);
  return null;
}

const out = {};
const missing = [];
for (const [logical, candidates] of Object.entries(MAP)) {
  const base = candidates.find((c) => VARIANTS.every((v) => body(`${c}-${v}`)));
  if (!base) {
    missing.push(logical);
    continue;
  }
  out[logical] = Object.fromEntries(VARIANTS.map((v) => [v, body(`${base}-${v}`)]));
}
if (missing.length) {
  console.error("missing icons:", missing.join(", "));
  process.exit(1);
}
const header = `// Generated by scripts/gen-icons.mjs from Solar icons (CC BY 4.0, 480 Design).\n// Do not edit by hand.\n`;
writeFileSync(
  new URL("../src/icons.generated.ts", import.meta.url),
  `${header}export type IconVariant = ${VARIANTS.map((v) => JSON.stringify(v)).join(" | ")};\nexport type IconName = ${Object.keys(out).map((k) => JSON.stringify(k)).join(" | ")};\nexport const ICONS: Record<IconName, Record<IconVariant, string>> = ${JSON.stringify(out)};\n`,
);
console.log(`wrote ${Object.keys(out).length} icons × ${VARIANTS.length} variants`);
