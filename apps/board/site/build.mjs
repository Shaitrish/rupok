#!/usr/bin/env node
// Builds the static marketing pages from site/pages/*.mjs:
//   <path>/index.html   HTML page (a Vite input; listed in site/inputs.json)
//   public/<path>.md    clean Markdown twin for AI agents (linked from llms.txt)
//   public/sitemap.xml  every public page, with lastmod and hreflang
//   public/llms-full.txt  product facts + every page's Markdown
// The home page (/) is hand-written in index.html; only its Markdown is built here.
//
//   cd apps/board && node site/build.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SITE, UPDATED, faqHtml, footer, jsonLd, mdPath, pageHtml, pageMd, plansHtml } from "./lib.mjs";
import { homePlans } from "./pages/pricing.mjs";
import { HOME, PAGES } from "./pages/index.mjs";
import { FACTS } from "./pages/facts.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const write = (rel, text) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
};

const inputs = [];
for (const { page, source } of PAGES) {
  if (page.html !== false) {
    const rel = page.path.slice(1) + "index.html";
    write(rel, pageHtml(page, source));
    inputs.push(rel);
  }
  write(join("public", mdPath(page)), pageMd(page));
}
write("site/inputs.json", JSON.stringify(inputs, null, 2) + "\n");

// ------------------------------------------------------------- home page
// index.html is hand-written (and edited by others): only the regions between
// <!-- site:NAME --> and <!-- /site:NAME --> are replaced.
{
  const file = join(root, "index.html");
  const before = readFileSync(file, "utf8");
  let html = before;
  const regions = {
    head: [
      `<link rel="alternate" hreflang="en" href="${SITE}/" />`,
      `<link rel="alternate" hreflang="bn" href="${SITE}/bn/" />`,
      `<link rel="alternate" hreflang="x-default" href="${SITE}/" />`,
      `<link rel="alternate" type="text/markdown" href="/index.md" title="Markdown version" />`,
      jsonLd(HOME, { home: true }),
    ].join("\n    "),
    faq: faqHtml(HOME),
    plans: plansHtml(homePlans("en")),
    footer: footer(HOME),
  };
  for (const [name, body] of Object.entries(regions)) {
    const re = new RegExp(`(<!-- site:${name}\\b[^>]*-->)[\\s\\S]*?(<!-- /site:${name} -->)`);
    if (!re.test(html)) {
      console.warn(`index.html: no <!-- site:${name} --> region, skipped`);
      continue;
    }
    html = html.replace(re, (_, a, b) => `${a}\n    ${body}\n    ${b}`);
  }
  if (html !== before) writeFileSync(file, html);
}

// ------------------------------------------------------------ agent skill
// skills/read-rpk/ (Apache-2.0) is served as /skills/read-rpk.md, with its
// script and sample lesson, so a model given only a link can read a .rpk.
{
  const skill = join(root, "../../skills/read-rpk");
  write("public/skills/read-rpk.md", readFileSync(join(skill, "SKILL.md"), "utf8"));
  write("public/skills/read_rpk.py", readFileSync(join(skill, "read_rpk.py"), "utf8"));
  const p = join(root, "public/skills/sample-lesson.rpk");
  writeFileSync(p, readFileSync(join(skill, "tests/sample-lesson.rpk")));
}

// ---------------------------------------------------------------- sitemap
const entries = [...PAGES.map(({ page }) => page), { path: "/board/", lang: "en", updated: UPDATED, priority: "0.8" }];
const order = (p) => (p.path === "/" ? 0 : p.path === "/bn/" ? 1 : p.path.split("/").length);
entries.sort((a, b) => order(a) - order(b) || a.path.localeCompare(b.path));
const urls = entries.map((p) => {
  const alts = p.alt
    ? Object.entries({ [p.lang]: p.path, ...p.alt })
        .map(([l, path]) => `\n    <xhtml:link rel="alternate" hreflang="${l}" href="${SITE + path}"/>`)
        .join("") + `\n    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE + (p.lang === "en" ? p.path : p.alt.en)}"/>`
    : "";
  return `  <url>\n    <loc>${SITE + p.path}</loc>\n    <lastmod>${p.updated ?? UPDATED}</lastmod>${alts}\n  </url>`;
});
write(
  "public/sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by apps/board/site/build.mjs -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls.join("\n")}\n</urlset>\n`,
);

// ------------------------------------------------------------ llms-full
const full = [FACTS.trim(), "", "---", "", "# Pages", "", ...PAGES.flatMap(({ page }) => [pageMd(page).trim(), "", "---", ""])].join("\n");
write("public/llms-full.txt", full);

console.log(`built ${inputs.length} pages, ${PAGES.length} markdown files, sitemap (${entries.length} urls), llms-full.txt`);
